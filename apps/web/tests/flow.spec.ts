import { test, expect } from '@playwright/test'
import path from 'node:path'

test('desktop recommendation, evidence, comparison and reload', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.getByRole('button', { name: '演示体验', exact: true }).click()
  await expect(page.getByRole('button', { name: '帮我挑选' })).toBeEnabled()
  await page.screenshot({ path: path.resolve('../../evaluations/screenshots/desktop-home.png'), fullPage: true })
  await page.getByRole('button', { name: '帮我挑选' }).click()
  await expect(page.getByRole('alert')).toContainText('先选择')
  await page.getByRole('button', { name: '键盘 + 鼠标', exact: true }).click()
  await page.getByLabel('还有什么在意的？').fill('宿舍用，必须蓝牙，希望安静')
  await page.getByRole('button', { name: '帮我挑选' }).click()
  await expect(page.getByRole('heading', { name: '这是我理解的需求' })).toBeVisible()
  await page.getByRole('button', { name: '确认需求，查看方案' }).click()
  await expect(page.getByRole('heading', { name: '3 套值得考虑的方案' })).toBeVisible()
  await page.getByRole('button', { name: /对比/ }).click()
  await expect(page.getByRole('table')).toBeVisible()
  await page.screenshot({ path: path.resolve('../../evaluations/screenshots/desktop-result.png'), fullPage: true })
  await page.getByRole('button', { name: /推荐依据/ }).click()
  await expect(page.getByRole('dialog')).toContainText('模拟资料')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('button', { name: '真实资料', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('tablist')).toHaveCount(0)
  await page.getByRole('button', { name: '演示体验', exact: true }).click()
  await expect(page.getByRole('heading', { name: '3 套值得考虑的方案' })).toBeVisible()
  await page.getByLabel('你的总预算').fill('1')
  await page.getByRole('button', { name: '按新需求重新挑选' }).click()
  await page.getByRole('button', { name: '确认需求，查看方案' }).click()
  await expect(page.getByRole('heading', { name: '暂时没有合适的组合' })).toBeVisible()
  expect(errors).toEqual([])
})

