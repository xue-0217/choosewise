test('real samples are default and incomplete prices never show demo recommendations', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await expect(page.getByRole('button', { name: '真实资料', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('heading', { name: 'Pebble Keys 2 K380s', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'M240 轻音蓝牙鼠标', exact: true })).toBeVisible()
  await expect(page.getByText('价格待补充', { exact: true })).toHaveCount(2)
  const links = await page.locator('.real-source a').evaluateAll(elements => elements.map(element => (element as HTMLAnchorElement).href))
  expect(links).toHaveLength(2)
  expect(links.every(link => link.startsWith('https://www.logitech.com/zh-cn/shop/p/'))).toBeTruthy()
  await page.screenshot({ path: path.resolve('../../evaluations/screenshots/real-catalog-home.png'), fullPage: true })
  await page.getByRole('button', { name: '键盘', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'M240 轻音蓝牙鼠标', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '检查真实推荐资料' }).click()
  await page.getByRole('button', { name: '确认需求，检查资料' }).click()
  await expect(page.getByRole('heading', { name: '真实推荐资料还需补齐' })).toBeVisible()
  await expect(page.locator('.products-grid')).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Pebble Keys 2 K380s', exact: true })).toBeVisible()
  await expect(page.locator('.result-panel')).not.toContainText(/\bM[12]\b/)
  await page.reload()
  await expect(page.getByRole('heading', { name: '真实推荐资料还需补齐' })).toBeVisible()
})

for (const width of [390, 1440, 1920]) {
  test(`all scheme illustrations fit cards at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 1000 })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.goto('/')
    await page.getByRole('button', { name: '演示体验', exact: true }).click()
    for (const target of ['键盘', '鼠标', '键盘 + 鼠标']) {
      await page.getByRole('button', { name: target, exact: true }).click()
      await page.locator('#budget').fill('350')
      await page.locator('.needs-panel .primary-button').click()
      await page.getByRole('button', { name: '确认需求，查看方案' }).click()
      await expect(page.getByRole('heading', { name: '3 套值得考虑的方案' })).toBeVisible()
      for (let index = 0; index < 3; index++) {
        await page.getByRole('tab').nth(index).click()
        await expect(page.locator('.product')).toHaveCount(target === '键盘 + 鼠标' ? 2 : 1)
        const geometry = await page.locator('.product').evaluateAll(products => products.map(product => {
          const slot = product.querySelector('.product-visual')!.getBoundingClientRect()
          const art = product.querySelector('.product-visual>svg')!.getBoundingClientRect()
          const title = product.querySelector('h3')!.getBoundingClientRect()
          return { contained: art.left >= slot.left - 1 && art.right <= slot.right + 1 && art.top >= slot.top - 1 && art.bottom <= slot.bottom + 1, clearTitle: art.bottom <= title.top, height: art.height, slotHeight: slot.height }
        }))
        for (const item of geometry) {
          expect(item.contained, JSON.stringify(item)).toBeTruthy()
          expect(item.clearTitle).toBeTruthy()
        }
        expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
      }
      if (target === '键盘') await page.locator('.featured-scheme').screenshot({ path: path.resolve(`../../evaluations/screenshots/keyboard-card-${width}.png`) })
    }
    await page.getByRole('button', { name: '真实资料', exact: true }).click()
    await expect(page.getByRole('tablist')).toHaveCount(0)
    await expect(page.locator('.product')).toHaveCount(0)
    await expect(page.getByRole('heading', { name: '真实商品资料' })).toBeVisible()
  })
}
